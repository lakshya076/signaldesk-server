  USING ((((get_role() = 'advisor'::text) AND (auth.uid() = advisor_id)) OR ((get_role() = 'user'::text) AND (advisor_id IN ( SELECT s.advisor_id
   FROM subscriptions s
  WHERE (s.user_id = auth.uid()))))));
