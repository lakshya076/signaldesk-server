-- ==================== Functions ====================
CREATE OR REPLACE FUNCTION public.get_role()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  RETURN (
    SELECT role FROM public.profiles WHERE id = auth.uid()
  );
END;
$function$
;
CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  user_role TEXT;
BEGIN
  -- Insert a new row into public.profiles with only the essential info
  INSERT INTO public.profiles (id, email, role)
  VALUES (
    new.id,
    new.email,
    new.raw_user_meta_data->>'role'
  );

  user_role := new.raw_user_meta_data->>'role';

  -- Insert a corresponding empty row into the role-specific details table
  IF user_role = 'advisor' THEN
    INSERT INTO public.advisor_details (profile_id) VALUES (new.id);
  ELSIF user_role = 'user' THEN
    INSERT INTO public.user_details (profile_id) VALUES (new.id);
  END IF;
  
  RETURN new;
END;
$function$
;
CREATE OR REPLACE FUNCTION public.handle_statistics_update()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
  PERFORM public.update_platform_statistics();
  RETURN NULL; -- result is ignored since this is an AFTER trigger
END;
$function$
;
CREATE OR REPLACE FUNCTION public.handle_subscription_change()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  -- If a row is inserted (new subscription), update the advisor's stats
  IF (TG_OP = 'INSERT') THEN
    PERFORM public.update_advisor_stats(NEW.advisor_id);
    RETURN NEW;
  -- If a row is deleted (unsubscribed), update the advisor's stats
  ELSIF (TG_OP = 'DELETE') THEN
    PERFORM public.update_advisor_stats(OLD.advisor_id);
    RETURN OLD;
  END IF;
  RETURN NULL;
END;
$function$
;
CREATE OR REPLACE FUNCTION public.handle_trade_card_closure()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  -- Check if a trade is being updated from 'open' to a closed state
  IF (OLD.status = 'open' AND NEW.status != 'open') THEN
    -- Update the statistics for the advisor associated with the trade
    PERFORM public.update_advisor_stats(NEW.advisor_id);
  END IF;
  RETURN NEW;
END;
$function$
;
CREATE OR REPLACE FUNCTION public.update_advisor_stats(advisor_uuid uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  closed_trades_count int;
  profit_trades_count int;
  current_follower_count int;
  new_hit_rate numeric;
BEGIN
  -- Calculate trade statistics from the trade_cards table
  SELECT
    COUNT(*),
    COUNT(*) FILTER (WHERE status = 'closed_profit')
  INTO
    closed_trades_count,
    profit_trades_count
  FROM
    public.trade_cards
  WHERE
    advisor_id = advisor_uuid AND status != 'open';

  -- Calculate follower count from the subscriptions table
  SELECT
    COUNT(*)
  INTO
    current_follower_count
  FROM
    public.subscriptions
  WHERE
    advisor_id = advisor_uuid;

  -- Calculate the new hit rate, avoiding division by zero
  IF closed_trades_count > 0 THEN
    new_hit_rate := (profit_trades_count::numeric / closed_trades_count) * 100;
  ELSE
    new_hit_rate := 0.0;
  END IF;

  -- Insert or update the statistics in the advisor_statistics table
  INSERT INTO public.advisor_statistics (
    advisor_id,
    follower_count,
    total_closed_trades,
    profitable_trades,
    hit_rate
  )
  VALUES (
    advisor_uuid,
    current_follower_count,
    closed_trades_count,
    profit_trades_count,
    new_hit_rate
  )
  ON CONFLICT (advisor_id)
  DO UPDATE SET
    follower_count = EXCLUDED.follower_count,
    total_closed_trades = EXCLUDED.total_closed_trades,
    profitable_trades = EXCLUDED.profitable_trades,
    hit_rate = EXCLUDED.hit_rate;
END;
$function$
;
CREATE OR REPLACE FUNCTION public.update_platform_statistics()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
  thirty_days_ago timestamptz := now() - interval '30 days';
  seven_days_ago timestamptz := now() - interval '7 days';
BEGIN
  -- Use a CTE for date series to aggregate daily stats
  WITH daily_series AS (
    SELECT generate_series(
      date_trunc('day', seven_days_ago),
      date_trunc('day', now()),
      '1 day'::interval
    ) AS day
  )
  UPDATE public.platform_statistics
  SET
    -- User & Advisor Metrics
    total_users = (SELECT count(*) FROM public.profiles WHERE role = 'user'),
    total_advisors = (SELECT count(*) FROM public.profiles WHERE role = 'advisor'),
    new_users_last_30d = (SELECT count(*) FROM public.profiles WHERE role = 'user' AND created_at >= thirty_days_ago),
    new_advisors_last_30d = (SELECT count(*) FROM public.profiles WHERE role = 'advisor' AND created_at >= thirty_days_ago),
    
    -- Subscription Metrics
    total_subscriptions = (SELECT count(*) FROM public.subscriptions),
    
    -- Trade Metrics
    total_trades = (SELECT count(*) FROM public.trade_cards),
    open_trades = (SELECT count(*) FROM public.trade_cards WHERE status = 'open'),
    closed_trades_profit = (SELECT count(*) FROM public.trade_cards WHERE status = 'closed_profit'),
    closed_trades_loss = (SELECT count(*) FROM public.trade_cards WHERE status = 'closed_loss'),
    closed_trades_cost = (SELECT count(*) FROM public.trade_cards WHERE status = 'closed_cost'),

    -- JSONB Aggregated Metrics
    top_performing_advisors = (
      SELECT jsonb_agg(advisor_stats) FROM (
        SELECT p.first_name, p.last_name, s.hit_rate
        FROM public.advisor_statistics s
        JOIN public.profiles p ON s.advisor_id = p.id
        ORDER BY s.hit_rate DESC
        LIMIT 5
      ) AS advisor_stats
    ),
    most_traded_stocks = (
      SELECT jsonb_agg(stock_counts) FROM (
        SELECT stock_symbol, count(*) AS trade_count
        FROM public.trade_cards
        GROUP BY stock_symbol
        ORDER BY trade_count DESC
        LIMIT 5
      ) AS stock_counts
    ),
    
    -- Time-Series Metrics for Charts
    trades_created_last_7d = (
      SELECT jsonb_agg(daily_counts) FROM (
        SELECT ds.day::date AS date, COUNT(tc.id) AS count
        FROM daily_series ds
        LEFT JOIN public.trade_cards tc ON date_trunc('day', tc.created_at) = ds.day
        GROUP BY ds.day
        ORDER BY ds.day
      ) AS daily_counts
    ),
    user_registrations_last_7d = (
      SELECT jsonb_agg(daily_counts) FROM (
        SELECT ds.day::date AS date, COUNT(p.id) AS count
        FROM daily_series ds
        LEFT JOIN public.profiles p ON date_trunc('day', p.created_at) = ds.day
        GROUP BY ds.day
        ORDER BY ds.day
      ) AS daily_counts
    ),
    subscription_activity_last_7d = (
      SELECT jsonb_agg(daily_counts) FROM (
        SELECT ds.day::date AS date, COUNT(s.id) AS count
        FROM daily_series ds
        LEFT JOIN public.subscriptions s ON date_trunc('day', s.created_at) = ds.day
        GROUP BY ds.day
        ORDER BY ds.day
      ) AS daily_counts
    )
  WHERE id = TRUE;
END;
$function$
;

-- ==================== Triggers ====================
CREATE TRIGGER on_profile_change AFTER INSERT OR DELETE OR UPDATE ON public.profiles FOR EACH STATEMENT EXECUTE FUNCTION public.handle_statistics_update();
CREATE TRIGGER on_subscription_change AFTER INSERT OR DELETE ON public.subscriptions FOR EACH ROW EXECUTE FUNCTION public.handle_subscription_change();
CREATE TRIGGER on_subscription_change_for_stats AFTER INSERT OR DELETE OR UPDATE ON public.subscriptions FOR EACH STATEMENT EXECUTE FUNCTION public.handle_statistics_update();
CREATE TRIGGER on_trade_card_close AFTER UPDATE ON public.trade_cards FOR EACH ROW WHEN ((old.status IS DISTINCT FROM new.status)) EXECUTE FUNCTION public.handle_trade_card_closure();
CREATE TRIGGER on_trade_change AFTER INSERT OR DELETE OR UPDATE ON public.trade_cards FOR EACH STATEMENT EXECUTE FUNCTION public.handle_statistics_update();
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

