  USING ((auth.uid() = profile_id));
CREATE POLICY "Advisors can create their own watchlist items." ON public.watchlists AS PERMISSIVE FOR INSERT TO public
  WITH CHECK ((auth.uid() = advisor_id));
CREATE POLICY "Advisors can delete their own watchlist items." ON public.watchlists AS PERMISSIVE FOR DELETE TO public
  USING ((auth.uid() = advisor_id));
CREATE POLICY "Advisors can view their own watchlist." ON public.watchlists AS PERMISSIVE FOR SELECT TO public
  USING ((auth.uid() = advisor_id));

