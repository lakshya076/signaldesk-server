-- ==================== Policies ====================
CREATE POLICY "Advisors can create their own details." ON public.advisor_details AS PERMISSIVE FOR INSERT TO public
  WITH CHECK ((auth.uid() = profile_id));
CREATE POLICY "Advisors can update their own details." ON public.advisor_details AS PERMISSIVE FOR UPDATE TO public
  USING ((auth.uid() = profile_id));
CREATE POLICY "Any authenticated user can view advisor details." ON public.advisor_details AS PERMISSIVE FOR SELECT TO public
  USING (true);
CREATE POLICY "Advisor statistics are publicly viewable." ON public.advisor_statistics AS PERMISSIVE FOR SELECT TO public
  USING (true);
CREATE POLICY "Allow full access for authenticated users" ON public.advisor_statistics AS PERMISSIVE FOR ALL TO public
  USING ((auth.role() = 'authenticated'::text))
  WITH CHECK ((auth.role() = 'authenticated'::text));
CREATE POLICY "Admins can read platform statistics" ON public.platform_statistics AS PERMISSIVE FOR SELECT TO authenticated
  USING ((( SELECT profiles.role
   FROM profiles
  WHERE (profiles.id = auth.uid())) = 'admin'::text));
CREATE POLICY "Any authenticated user can view advisor profiles." ON public.profiles AS PERMISSIVE FOR SELECT TO public
  USING (true);
CREATE POLICY "Users can update their own profile." ON public.profiles AS PERMISSIVE FOR UPDATE TO public
  USING ((auth.uid() = id));
CREATE POLICY "Users can view their own profile." ON public.profiles AS PERMISSIVE FOR SELECT TO public
  USING ((auth.uid() = id));
CREATE POLICY "Users can create their own subscriptions." ON public.subscriptions AS PERMISSIVE FOR INSERT TO public
  WITH CHECK ((auth.uid() = user_id));
CREATE POLICY "Users can delete their own subscriptions." ON public.subscriptions AS PERMISSIVE FOR DELETE TO public
  USING ((auth.uid() = user_id));
CREATE POLICY "Users can view their own subscriptions." ON public.subscriptions AS PERMISSIVE FOR SELECT TO public
  USING ((auth.uid() = user_id));
CREATE POLICY "Advisors can create their own trade cards." ON public.trade_cards AS PERMISSIVE FOR INSERT TO public
  WITH CHECK (((get_role() = 'advisor'::text) AND (auth.uid() = advisor_id)));
CREATE POLICY "Advisors can delete their own trade cards." ON public.trade_cards AS PERMISSIVE FOR DELETE TO public
  USING (((get_role() = 'advisor'::text) AND (auth.uid() = advisor_id)));
CREATE POLICY "Advisors can update their own trade cards." ON public.trade_cards AS PERMISSIVE FOR UPDATE TO public
  USING (((get_role() = 'advisor'::text) AND (auth.uid() = advisor_id)));
